"""Generate the browser resolver's allowlist from validated methods.yml. No network.

Run from the repository root; --check is strictly read-only. Common's existing
generated metadata bytes and all authored method identities remain unchanged.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'BESHstatNG/tools'))
from validate_methods_catalog import _load_yaml, validate_catalog

YAML = ROOT / 'BESHStatNG_Help_MkDocs/docs/_meta/methods.yml'
OUTPUT = ROOT / 'BESHStatNG_Help_MkDocs/docs/assets/javascripts/help-routes.mjs'


def render():
    errors, _ = validate_catalog(ROOT)
    if errors:
        raise ValueError('\n'.join(errors))
    meta = _load_yaml(YAML)
    routes = {'Home': ''}
    routes.update({m['key']: f'methods/{m["slug"]}/' for m in meta['methods']})
    routes.update({p['key']: f'{p["slug"]}/' for p in meta['pages']})
    return ('// Generated by generate_help_resolver_routes.py; do not edit.\n'
            f'// methods.yml SHA256: {hashlib.sha256(YAML.read_bytes()).hexdigest()}\n'
            f'export const root = {json.dumps(meta["site"]["baseUrl"] + "/")};\n'
            f'export const routes = Object.freeze({json.dumps(routes, indent=2, ensure_ascii=True)});\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding='utf-8') != expected:
            raise SystemExit('FAIL: resolver route metadata absent/stale')
        print('PASS: resolver route metadata current (read-only)')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected, encoding='utf-8', newline='\n')
        print(f'Wrote {args.output}')


if __name__ == '__main__':
    main()
