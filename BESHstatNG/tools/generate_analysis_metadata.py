#!/usr/bin/env python3
"""Batch 00.02B: build deterministic, read-only Common metadata from methods.yml.

The generated catalog is *descriptive*, never an executable analysis registry.
The VB analysis IDs, typed options and handler registrations remain authoritative
for runtime execution. Requires PyYAML (same prerequisite as 00.02A).
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

from validate_methods_catalog import _load_yaml, _read_registered_ids, validate_catalog

DEFAULT_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_REL = Path('BESHStat.Excel.Common/src/Analysis/GeneratedMethodMetadata.vb')
YAML_REL = Path('BESHStatNG_Help_MkDocs/docs/_meta/methods.yml')


def _vb_literal(value: str | None) -> str:
    if value is None:
        return 'Nothing'
    # Escape quotes; normalize any line endings to a single VB string literal.
    return '"' + value.replace('"', '""').replace('\r', ' ').replace('\n', ' ') + '"'


def _plain_description(value: str) -> str:
    # The YAML short field contains lightweight Markdown for the website.
    # A plain text descriptor must not contain literal ** or newlines in a dropdown.
    return re.sub(r'\s+', ' ', value.replace('**', '').replace('`', '')).strip()


def render_catalog(root: Path) -> str:
    root = root.resolve()
    problems, _ = validate_catalog(root)
    if problems:
        raise ValueError('Cannot generate from invalid methods.yml:\n' + '\n'.join(problems))
    yaml_file = root / YAML_REL
    catalog = _load_yaml(yaml_file)
    methods = catalog['methods']
    base_url = str(catalog['site']['baseUrl']).rstrip('/')
    runtime_ids = set(_read_registered_ids(root / 'BESHStat.Excel.Common/src/Analysis/AnalysisIds.vb').values())
    published_ids = [m['analysisId'] for m in methods if m.get('analysisId')]
    if set(published_ids) != runtime_ids:
        raise ValueError(f'method analysisIds {sorted(published_ids)} do not match registered VB IDs {sorted(runtime_ids)}')
    source_hash = hashlib.sha256(yaml_file.read_bytes()).hexdigest()
    lines = [
        "' <auto-generated>",
        "' Batch 00.02B. Generated by BESHstatNG/tools/generate_analysis_metadata.py.",
        f"' methods.yml SHA256: {source_hash}",
        "' Do not edit. Does not register executable analysis handlers.",
        "' </auto-generated>",
        'Option Explicit On', 'Option Strict On', '',
        'Imports System', 'Imports System.Collections.Generic', '',
        'Namespace ExcelCommon', '',
        '    Public NotInheritable Class AnalysisMethodMetadata',
        '        Public Sub New(key As String, analysisId As String, displayName As String, category As String, description As String, helpUrl As String)',
        '            Me.Key = key', '            Me.AnalysisId = analysisId', '            Me.DisplayName = displayName',
        '            Me.Category = category', '            Me.Description = description', '            Me.HelpUrl = helpUrl',
        '        End Sub',
        '        Public ReadOnly Property Key As String',
        '        Public ReadOnly Property AnalysisId As String',
        '        Public ReadOnly Property DisplayName As String',
        '        Public ReadOnly Property Category As String',
        '        Public ReadOnly Property Description As String',
        '        Public ReadOnly Property HelpUrl As String',
        '    End Class', '',
        '    Public NotInheritable Class GeneratedMethodMetadata',
        '        Private Sub New()', '        End Sub', '',
        '        Private Shared ReadOnly _all As IReadOnlyList(Of AnalysisMethodMetadata) = Build()',
        '        Private Shared ReadOnly _byKey As Dictionary(Of String, AnalysisMethodMetadata) = IndexByKey(_all)',
        '        Private Shared ReadOnly _byAnalysisId As Dictionary(Of String, AnalysisMethodMetadata) = IndexByAnalysisId(_all)',
        '',
        '        Public Shared ReadOnly Property All As IReadOnlyList(Of AnalysisMethodMetadata)',
        '            Get', '                Return _all', '            End Get', '        End Property', '',
        '        Public Shared Function GetByKey(key As String) As AnalysisMethodMetadata',
        '            If key Is Nothing Then Throw New ArgumentNullException(NameOf(key))',
        '            Return _byKey(key)', '        End Function', '',
        '        Public Shared Function TryGetByAnalysisId(id As String, ByRef metadata As AnalysisMethodMetadata) As Boolean',
        '            metadata = Nothing',
        '            Return id IsNot Nothing AndAlso _byAnalysisId.TryGetValue(id, metadata)',
        '        End Function', '',
        '        Public Shared Function GetByAnalysisId(id As String) As AnalysisMethodMetadata',
        '            Dim metadata As AnalysisMethodMetadata = Nothing',
        '            If Not TryGetByAnalysisId(id, metadata) Then Throw New KeyNotFoundException("Unknown analysis ID: " & If(id, "(null)"))',
        '            Return metadata', '        End Function', '',
        '        Private Shared Function Build() As IReadOnlyList(Of AnalysisMethodMetadata)',
        '            Dim entries As AnalysisMethodMetadata() = {',
    ]
    # Stable authored order; no dependence on filesystem iteration or timestamps.
    for idx, method in enumerate(methods):
        fields = [method['key'], method.get('analysisId'), method['title'], method['categories'][0],
                  _plain_description(method['short']), f"{base_url}/latest/methods/{method['slug']}/"]
        suffix = ',' if idx != len(methods) - 1 else ''
        lines.append('                New AnalysisMethodMetadata(' + ', '.join(_vb_literal(f) for f in fields) + ')' + suffix)
    lines += [
        '            }', '            Return Array.AsReadOnly(entries)', '        End Function', '',
        '        Private Shared Function IndexByKey(items As IEnumerable(Of AnalysisMethodMetadata)) As Dictionary(Of String, AnalysisMethodMetadata)',
        '            Dim result As New Dictionary(Of String, AnalysisMethodMetadata)(StringComparer.Ordinal)',
        '            For Each item As AnalysisMethodMetadata In items',
        '                result.Add(item.Key, item)',
        '            Next', '            Return result', '        End Function', '',
        '        Private Shared Function IndexByAnalysisId(items As IEnumerable(Of AnalysisMethodMetadata)) As Dictionary(Of String, AnalysisMethodMetadata)',
        '            Dim result As New Dictionary(Of String, AnalysisMethodMetadata)(StringComparer.Ordinal)',
        '            For Each item As AnalysisMethodMetadata In items',
        '                If item.AnalysisId IsNot Nothing Then result.Add(item.AnalysisId, item)',
        '            Next', '            Return result', '        End Function',
        '    End Class', '', 'End Namespace', '',
    ]
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT, help='Solution root')
    parser.add_argument('--check', action='store_true', help='Exit nonzero if generated VB is absent/stale; never modify it')
    parser.add_argument('--output', type=Path, default=None, help='Override generated file path (primarily for verification)')
    args = parser.parse_args()
    try:
        result = render_catalog(args.root)
    except (OSError, ValueError) as exc:
        print(f'ERROR: {exc}')
        return 1
    output = args.output.resolve() if args.output else args.root.resolve() / OUTPUT_REL
    if args.check:
        if not output.is_file() or output.read_text(encoding='utf-8-sig') != result:
            print(f'FAIL: generated metadata is absent/stale: {output}')
            return 1
        print(f'PASS: generated metadata is current: {output}')
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(result, encoding='utf-8', newline='\n')
    print(f'Wrote {output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
