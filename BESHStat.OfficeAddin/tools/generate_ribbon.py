"""Reconcile actual Windows Ribbon and authored catalog; generate Office projections.
No Windows callback is executable here. Run with --check in verification tests.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape
import yaml

ROOT = Path(__file__).resolve().parents[2]
RIBBON = ROOT / 'BESHstatNG/Resources/RibbonXML.xml'
CATALOG = ROOT / 'BESHStatNG_Help_MkDocs/docs/_meta/methods.yml'
SUPPORTED = {'anova.oneway': 'BeshAnova', 'nonparametric.kruskal-wallis': 'BeshKruskal'}
UTILITIES = {'About': ('about', 'BeshAbout'), 'Help': ('help', 'BeshHelp'), 'Settings': ('options', 'BeshSettings'),
             'ShowLog': ('diagnostics', 'BeshLog'), 'ExportChart': ('export', 'BeshUnavailable')}

def inventory(ribbon=RIBBON, catalog=CATALOG):
    data = yaml.safe_load(catalog.read_text(encoding='utf-8'))
    methods = data['methods']; commands = data['commands']
    mapped = {}
    for kind, items in [('method', methods), ('utility', commands)]:
        for m in items:
            for rid in m.get('ribbonIds', [m.get('ribbonId')]):
                if rid is None: continue
                if rid in mapped: raise ValueError('Duplicate authored Ribbon ID: ' + rid)
                mapped[rid] = (kind, m)
    ns = {'r': 'http://schemas.microsoft.com/office/2009/07/customui'}
    tree = ET.parse(ribbon); parent = {child: node for node in tree.iter() for child in node}
    rows = []; seen = set(); categories = []
    for button in tree.findall('.//r:button', ns):
        rid = button.attrib['id']
        if rid in seen: raise ValueError('Duplicate physical Ribbon ID: '+rid)
        seen.add(rid)
        if rid not in mapped: raise ValueError('Unmapped Windows Ribbon ID: '+rid)
        kind, m = mapped[rid]; category = parent[button].get('label', 'Utilities') if kind == 'method' else 'Utilities'
        if kind == 'method' and category not in categories: categories.append(category)
        callbacks = m.get('onActions', [m.get('onAction')])
        if button.attrib['onAction'] not in callbacks: raise ValueError('Callback mismatch: '+rid)
        analysis = m.get('analysisId'); available = analysis in SUPPORTED if kind == 'method' else m['key'] != 'ExportChart'
        destination, function = ('analysis', SUPPORTED.get(analysis, 'BeshUnavailable')) if kind == 'method' else UTILITIES[m['key']]
        rows.append(dict(windowsId=rid, category=category, caption=button.attrib['label'], callback=button.attrib['onAction'],
            catalogKey=m['key'], analysisId=analysis, kind=kind, commandId=('method.'+m['key'] if kind == 'method' else destination),
            manifestId='Besh.'+rid, officeGroup='Besh.Analysis'+str((categories.index(category)//4)+1) if kind == 'method' else 'Besh.Workspace',
            function=function, destination=destination, available=available,
            capability='registered-editor/ExcelApi1.17' if kind == 'method' and available else 'utility' if available else 'not-implemented',
            disposition='editor-only; explicit Run/Write' if kind == 'method' and available else 'working utility' if available else 'disabled; no execution'))
    if set(mapped) != seen: raise ValueError('Authored Ribbon IDs absent in XML: '+str(sorted(set(mapped)-seen)))
    missing = {m['key'] for m in methods} - {r['catalogKey'] for r in rows if r['kind']=='method'}
    if missing: raise ValueError('Catalog methods without Ribbon mapping: '+str(sorted(missing)))
    repeated = {m['key']: [r['windowsId'] for r in rows if r['catalogKey']==m['key']] for m in methods}
    return dict(schemaVersion=1, sources={'ribbonSha256':hashlib.sha256(ribbon.read_bytes()).hexdigest(),
        'catalogSha256':hashlib.sha256(catalog.read_bytes()).hexdigest()}, categories=categories, occurrences=rows,
        summary={'buttons':len(rows),'methodOccurrences':sum(r['kind']=='method' for r in rows),'methods':len(methods),
                 'utilities':len(commands),'categories':len(categories)},
        repeatedMethods={k:v for k,v in repeated.items() if len(v)>1}, omissions=[], unknownIds=[])

def projections(ledger):
    rows = ledger['occurrences']
    cs = '// Generated by tools/generate_ribbon.py; do not hand edit.\nnamespace BESHStat.OfficeAddin.Services;\n'
    cs += 'public sealed record RibbonSource(string WindowsId, string Category, string Caption, string Callback, string CatalogKey, string CommandId, string ManifestId);\n'
    cs += 'public static class GeneratedRibbonCommands { public static readonly System.Collections.Generic.IReadOnlyList<RibbonSource> All = System.Array.AsReadOnly(new RibbonSource[] {\n'
    for r in rows: cs += '    new('+', '.join(json.dumps(r[k], ensure_ascii=True) for k in ['windowsId','category','caption','callback','catalogKey','commandId','manifestId'])+'),\n'
    cs += '}); }\n'
    shorts = {}; longs = {}
    def label(key, value): shorts[key] = value; return f'<Label resid="{key}"/>'
    def tip(key, title, description):
        shorts[key+'.Title'] = title[:125]; longs[key+'.Tip'] = description[:250]
        return f'<Supertip><Title resid="{key}.Title"/><Description resid="{key}.Tip"/></Supertip>'
    icon = '<Icon>'+''.join(f'<bt:Image size="{s}" resid="Icon.{s}"/>' for s in (16,32,80))+'</Icon>'
    def action(row): return f'<Action xsi:type="ExecuteFunction"><FunctionName>{row["function"]}</FunctionName></Action><Enabled>{str(row["available"]).lower()}</Enabled>'
    groups = []
    workspace = '<Group id="Besh.Workspace">'+label('Workspace.Label','BESHStatNG')+icon
    workspace += '<Control xsi:type="Button" id="Besh.Open">'+label('Open.Label','Open BESHStatNG')+tip('Open','Open BESHStatNG','Open the existing analysis workspace. No analysis runs automatically.')+icon+'<Action xsi:type="ShowTaskpane"><SourceLocation resid="Taskpane.Url"/></Action></Control>'
    for i, r in enumerate(r for r in rows if r['kind']=='utility'):
        caption = r['caption'] if r['catalogKey']!='ExportChart' else 'Export Chart (unavailable)'
        workspace += f'<Control xsi:type="Button" id="{r["manifestId"]}">'+label('U'+str(i)+'.Label',caption)+tip('U'+str(i),caption,'Chart export is not implemented in Office.' if not r['available'] else 'Open '+r['destination']+' in this BESHStatNG pane.')+icon+action(r)+'</Control>'
    groups.append(workspace+'</Group>')
    for g in range(3):
        group = f'<Group id="Besh.Analysis{g+1}">'+label(f'G{g}.Label','Analysis '+str(g+1))+icon
        for ci, category in enumerate(ledger['categories']):
            if ci//4 != g: continue
            group += f'<Control xsi:type="Menu" id="Besh.Category{ci}">'+label(f'C{ci}.Label',category)+tip(f'C{ci}',category,'Only ANOVA and Kruskal-Wallis have Office editors. Other entries are disabled.')+icon+'<Items>'
            for ri,r in enumerate(rows):
                if r['kind']!='method' or r['category']!=category: continue
                caption = r['caption'] + ('' if r['available'] else ' (not yet available)')
                group += f'<Item id="{r["manifestId"]}">'+label(f'M{ri}.Label',caption[:125])+tip(f'M{ri}',r['caption'],'Open the supported editor; no automatic calculation.' if r['available'] else 'Not yet available in Office. The specification builder is read-only, not a fitted method.')+icon+action(r)+'</Item>'
            group += '</Items></Control>'
        groups.append(group+'</Group>')
    xml = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated development manifest. Identity/base URL preserved; sideload only. -->
<OfficeApp xmlns="http://schemas.microsoft.com/office/appforoffice/1.1" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:bt="http://schemas.microsoft.com/office/officeappbasictypes/1.0" xsi:type="TaskPaneApp">
<Id>5f70b95c-dc4a-4f38-b78d-0a7348657e19</Id><Version>1.0.1.0</Version><ProviderName>BESHStatNG</ProviderName><DefaultLocale>en-US</DefaultLocale>
<DisplayName DefaultValue="BESHStatNG Office workspace"/><Description DefaultValue="BESHStatNG development analysis workspace and capability-guarded Ribbon commands."/>
<IconUrl DefaultValue="https://localhost:7141/icons/ribbon-32.png"/><HighResolutionIconUrl DefaultValue="https://localhost:7141/icons/ribbon-80.png"/>
<SupportUrl DefaultValue="https://www.beshstat.eu/beshstatng/help/latest/"/>
<Hosts><Host Name="Workbook"/></Hosts><Requirements><Sets DefaultMinVersion="1.1"><Set Name="ExcelApi" MinVersion="1.1"/></Sets></Requirements>
<DefaultSettings><SourceLocation DefaultValue="https://localhost:7141/"/></DefaultSettings><Permissions>ReadWriteDocument</Permissions>
<VersionOverrides xmlns="http://schemas.microsoft.com/office/taskpaneappversionoverrides" xsi:type="VersionOverridesV1_0">
<Requirements><bt:Sets DefaultMinVersion="1.1"><bt:Set Name="AddinCommands" MinVersion="1.1"/><bt:Set Name="SharedRuntime" MinVersion="1.1"/><bt:Set Name="RibbonApi" MinVersion="1.1"/></bt:Sets></Requirements>
<Hosts><Host xsi:type="Workbook"><Runtimes><Runtime resid="Taskpane.Url" lifetime="long"/></Runtimes><DesktopFormFactor>
<FunctionFile resid="Taskpane.Url"/><ExtensionPoint xsi:type="PrimaryCommandSurface"><CustomTab id="Besh.Tab">
'''+''.join(groups)+label('Tab.Label','BESHStatNG')+'''</CustomTab></ExtensionPoint></DesktopFormFactor></Host></Hosts><Resources><bt:Images>'''
    xml += ''.join(f'<bt:Image id="Icon.{s}" DefaultValue="https://localhost:7141/icons/ribbon-{s}.png"/>' for s in (16,32,80))
    xml += '</bt:Images><bt:Urls><bt:Url id="Taskpane.Url" DefaultValue="https://localhost:7141/"/></bt:Urls><bt:ShortStrings>'
    xml += ''.join(f'<bt:String id="{k}" DefaultValue="{escape(v, {chr(34): "&quot;"})}"/>' for k,v in shorts.items())
    xml += '</bt:ShortStrings><bt:LongStrings>'+''.join(f'<bt:String id="{k}" DefaultValue="{escape(v, {chr(34): "&quot;"})}"/>' for k,v in longs.items())+'</bt:LongStrings></Resources></VersionOverrides></OfficeApp>'
    tree=ET.fromstring(xml); ET.indent(tree,space='  ')
    serialized=ET.tostring(tree,encoding='unicode')
    # xsi:type is a QName: its unprefixed value must resolve in the override namespace.
    serialized=serialized.replace(' xmlns:ov="http://schemas.microsoft.com/office/taskpaneappversionoverrides"','')
    serialized=serialized.replace('<ov:VersionOverrides','<VersionOverrides xmlns="http://schemas.microsoft.com/office/taskpaneappversionoverrides"').replace('ov:','')
    return cs, '<?xml version="1.0" encoding="utf-8"?>\n'+serialized+'\n'

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    for prefix,uri in [('', 'http://schemas.microsoft.com/office/appforoffice/1.1'),('xsi','http://www.w3.org/2001/XMLSchema-instance'),('bt','http://schemas.microsoft.com/office/officeappbasictypes/1.0'),('ov','http://schemas.microsoft.com/office/taskpaneappversionoverrides')]: ET.register_namespace(prefix,uri)
    ledger=inventory(); cs,xml=projections(ledger)
    outputs={'docs/architecture/batch-04-07-ribbon-parity.json':json.dumps(ledger,indent=2,ensure_ascii=False)+'\n',
             'BESHStat.OfficeAddin/Services/GeneratedRibbonCommands.cs':cs,'BESHStat.OfficeAddin/manifest-dev.xml':xml}
    for path,content in outputs.items():
        target=ROOT/path
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != content: raise SystemExit('Stale generated output: '+path)
        else: target.write_text(content,encoding='utf-8',newline='\n')
    print(json.dumps(ledger['summary']))
if __name__=='__main__': main()
